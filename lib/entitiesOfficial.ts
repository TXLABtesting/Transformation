/** الاسم المعتمد لجهة (يقبل الاسم القديم أو المعتمد) */
export const officialEntityName = (name: string): string => {
  const t = String(name || '').replace(/\s+/g, ' ').trim();
  return ENTITY_ALIASES[t] || t;
};

/** الأسماء القديمة التي تشير إلى جهة معتمدة (لقراءة دليل الخدمات) */
export const legacyNamesOf = (official: string): string[] =>
  Object.entries(ENTITY_ALIASES)
    .filter(([, v]) => v === official)
    .map(([k]) => k);

/** أسماء الجهات ضمن النطاق (بلا الجهات المعلّقة) بترتيب الوثيقة */
export const OFFICIAL_ENTITY_NAMES: string[] = OFFICIAL_ENTITIES.filter((e) => !e.pending).map((e) => e.name);

export const entityCategoryOf = (name: string): EntityCategory | null =>
  OFFICIAL_ENTITIES.find((e) => e.name === officialEntityName(name))?.category ?? null;
